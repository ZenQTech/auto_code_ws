interface HelmTabProps {
  files: Record<string, string>;
  options: ApplicationStackOptions;
  onChange: (opts: ApplicationStackOptions) => void;
}

function HelmTab({ files, options, onChange }: HelmTabProps) {
  const [selectedFile, setSelectedFile] = useState<string>('');
  const fileList = Object.keys(files).sort();
  const currentFile = selectedFile || fileList[0] || '';
  const currentContent = files[currentFile] || '';

  return (
    <div className="grid grid-cols-1 lg:grid-cols-4 gap-4">
      {/* 文件列表 */}
      <div>
        <h3 className="text-sm font-semibold mb-2">Chart 文件 ({fileList.length})</h3>
        <div className="space-y-1 max-h-[500px] overflow-y-auto">
          {fileList.map((f) => (
            <button
              key={f}
              onClick={() => setSelectedFile(f)}
              className={`w-full text-left px-2 py-1 text-xs rounded ${
                currentFile === f
                  ? 'bg-blue-100 dark:bg-blue-900/30 text-blue-700 dark:text-blue-300'
                  : 'hover:bg-gray-100 dark:hover:bg-gray-800 text-gray-700 dark:text-gray-300'
              }`}
            >
              📄 {f}
            </button>
          ))}
        </div>
      </div>

      {/* 文件内容 */}
      <div className="lg:col-span-3">
        <div className="flex items-center justify-between mb-2">
          <h3 className="text-sm font-semibold">{currentFile}</h3>
          <button
            onClick={() => navigator.clipboard?.writeText(currentContent)}
            className="px-2 py-1 text-xs bg-blue-500 text-white rounded hover:bg-blue-600"
          >
            复制
          </button>
        </div>
        <pre className="bg-gray-50 dark:bg-gray-800 border border-gray-200 dark:border-gray-700 rounded p-3 text-xs overflow-auto h-[500px]">
          {currentContent}
        </pre>
      </div>
    </div>
  );
}

