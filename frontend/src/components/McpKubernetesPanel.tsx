import { useState, useMemo } from 'react';
import {
  buildApplicationStack,
  type ApplicationStackOptions,
} from '../utils/kubernetes/k8sManifestGenerator';
import {
  buildHelmChart,
  packChartFiles,
  type BuildChartOptions,
} from '../utils/kubernetes/helmChartGenerator';
import {
  createMcpAgentCRD,
  createCustomResource,
  buildCRDManifest,
  buildCustomResourceYaml,
  generateRBACManifests,
  McpAgentSpecSchema,
} from '../utils/kubernetes/crdGenerator';
import { K8sApiClient, type K8sAuth } from '../utils/kubernetes/k8sApiClient';

export interface McpKubernetesPanelProps {
  /** 关闭回调 */
  onClose: () => void;
}

/** Tab 标识 */
type TabKey = 'manifest' | 'helm' | 'crd' | 'api' | 'docs';

/** 应用配置 state */
const DEFAULT_STACK: ApplicationStackOptions = {
  name: 'web',
  image: 'nginx:1.25',
  ports: [{ name: 'http', containerPort: 80 }],
  replicas: 3,
  enableHPA: true,
  hpaMin: 2,
  hpaMax: 10,
  enableIngress: true,
  ingressHost: 'web.example.com',
  configMapData: {
    LOG_LEVEL: 'info',
    MAX_CONNECTIONS: '1000',
  },
};

/** API 客户端配置 */
const DEFAULT_API_CONFIG = {
  apiServerUrl: 'https://api.example.com:6443',
  authType: 'bearer' as 'bearer' | 'basic' | 'serviceAccount' | 'anonymous',
  token: '',
  username: '',
  password: '',
  namespace: 'default',
  mode: 'mock' as 'mock' | 'real' | 'hybrid',
};

export default function McpKubernetesPanel({ onClose }: McpKubernetesPanelProps) {
  const [activeTab, setActiveTab] = useState<TabKey>('manifest');
  const [stackOptions, setStackOptions] = useState<ApplicationStackOptions>(DEFAULT_STACK);
  const [apiConfig, setApiConfig] = useState(DEFAULT_API_CONFIG);
  const [apiStatus, setApiStatus] = useState<{
    checking: boolean;
    healthy?: boolean;
    info?: string;
  }>({ checking: false });

  // 计算 manifest 输出
  const manifestYaml = useMemo(() => {
    try {
      const resources = buildApplicationStack(stackOptions);
      const resources_yaml = resources.map((r) => JSON.stringify(r, null, 2)).join('\n---\n');
      return resources_yaml;
    } catch (e) {
      return `# Error: ${e instanceof Error ? e.message : String(e)}`;
    }
  }, [stackOptions]);

  // 计算 Helm chart 输出
  const chartFiles = useMemo(() => {
    try {
      const chartOptions: BuildChartOptions = {
        ...stackOptions,
        chartVersion: '1.0.0',
        chartDescription: `${stackOptions.name} Helm chart generated by MCP × Kubernetes Panel`,
        maintainers: [{ name: 'MCP × Hermes Team', email: 'team@mcp-hermes.io' }],
        keywords: ['mcp', 'hermes', 'kubernetes'],
      };
      const pkg = buildHelmChart(chartOptions);
      return packChartFiles(pkg, stackOptions.name);
    } catch (e) {
      return { error: e instanceof Error ? e.message : String(e) } as unknown as Record<string, string>;
    }
  }, [stackOptions]);

  // CRD 输出
  const crdYaml = useMemo(() => {
    try {
      const crd = createMcpAgentCRD();
      return buildCRDManifest([crd]);
    } catch (e) {
      return `# Error: ${e instanceof Error ? e.message : String(e)}`;
    }
  }, []);

  // CR 实例输出
  const crInstanceYaml = useMemo(() => {
    try {
      const cr = createCustomResource({
        kind: 'McpAgent',
        group: 'mcp.hermes.io',
        version: 'v1',
        name: `${stackOptions.name}-agent`,
        namespace: stackOptions.namespace ?? 'default',
        spec: {
          image: stackOptions.image,
          replicas: stackOptions.replicas ?? 1,
          model: 'claude-sonnet-4.5',
          tools: ['rag-search', 'code-review', 'trace-query'],
          autoscaling: {
            enabled: stackOptions.enableHPA ?? false,
            minReplicas: stackOptions.hpaMin ?? 1,
            maxReplicas: stackOptions.hpaMax ?? 10,
          },
        },
        status: { phase: 'Running', readyReplicas: stackOptions.replicas ?? 1 },
      });
      return buildCustomResourceYaml(cr);
    } catch (e) {
      return `# Error: ${e instanceof Error ? e.message : String(e)}`;
    }
  }, [stackOptions]);

  // RBAC 输出
  const rbacYaml = useMemo(() => {
    try {
      const rbac = generateRBACManifests({
        name: 'mcpagent-controller',
        namespace: 'mcp-system',
        apiGroup: 'mcp.hermes.io',
        resource: 'mcpagents',
        verbs: ['get', 'list', 'watch', 'create', 'update', 'patch', 'delete'],
      });
      return [rbac.serviceAccount, rbac.role, rbac.roleBinding]
        .map((r) => JSON.stringify(r, null, 2))
        .join('\n---\n');
    } catch (e) {
      return `# Error: ${e instanceof Error ? e.message : String(e)}`;
    }
  }, []);

  // 测试 API 连接
  const handleTestConnection = async () => {
    setApiStatus({ checking: true });
    try {
      const auth: K8sAuth =
        apiConfig.authType === 'bearer'
          ? { type: 'bearer', token: apiConfig.token }
          : apiConfig.authType === 'basic'
            ? { type: 'basic', username: apiConfig.username, password: apiConfig.password }
            : { type: 'anonymous' };
      const client = new K8sApiClient({
        apiServerUrl: apiConfig.apiServerUrl,
        auth,
        namespace: apiConfig.namespace,
        mode: apiConfig.mode,
        timeoutMs: 10000,
      });
      const result = await client.healthCheck();
      if (result.healthy) {
        const info = await client.getClusterInfo();
        setApiStatus({
          checking: false,
          healthy: true,
          info: `${info.version} | ${info.nodes} nodes | ${info.namespaces} ns | ${info.pods} pods`,
        });
      } else {
        setApiStatus({ checking: false, healthy: false, info: result.error });
      }
    } catch (e) {
      setApiStatus({
        checking: false,
        healthy: false,
        info: e instanceof Error ? e.message : String(e),
      });
    }
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center bg-black/50 p-4">
      <div className="bg-white dark:bg-gray-900 rounded-lg shadow-2xl w-full max-w-7xl max-h-[90vh] flex flex-col">
        {/* Header */}
        <div className="flex items-center justify-between px-6 py-4 border-b border-gray-200 dark:border-gray-700">
          <div>
            <h2 className="text-xl font-bold text-gray-900 dark:text-gray-100">
              ☸️ MCP × Kubernetes 配置面板
            </h2>
            <p className="text-sm text-gray-500 dark:text-gray-400 mt-1">
              Cycle 55 G55-INTEGRATION | Manifest + Helm + CRD + API 集群编排
            </p>
          </div>
          <button
            onClick={onClose}
            className="px-3 py-1 text-sm bg-gray-100 hover:bg-gray-200 dark:bg-gray-800 dark:hover:bg-gray-700 rounded"
          >
            关闭
          </button>
        </div>

        {/* Tabs */}
        <div className="flex border-b border-gray-200 dark:border-gray-700 px-4 overflow-x-auto">
          {[
            { key: 'manifest', label: '📦 Manifest' },
            { key: 'helm', label: '⎈ Helm Chart' },
            { key: 'crd', label: '🧩 CRD/Operator' },
            { key: 'api', label: '🔌 API 客户端' },
            { key: 'docs', label: '📖 集成文档' },
          ].map((tab) => (
            <button
              key={tab.key}
              onClick={() => setActiveTab(tab.key as TabKey)}
              className={`px-4 py-2 text-sm font-medium whitespace-nowrap ${
                activeTab === tab.key
                  ? 'border-b-2 border-blue-500 text-blue-600 dark:text-blue-400'
                  : 'text-gray-500 dark:text-gray-400 hover:text-gray-700 dark:hover:text-gray-300'
              }`}
            >
              {tab.label}
            </button>
          ))}
        </div>

        {/* Content */}
        <div className="flex-1 overflow-y-auto p-6">
          {activeTab === 'manifest' && (
            <ManifestTab
              options={stackOptions}
              onChange={setStackOptions}
              yaml={manifestYaml}
            />
          )}
          {activeTab === 'helm' && (
            <HelmTab files={chartFiles} options={stackOptions} onChange={setStackOptions} />
          )}
          {activeTab === 'crd' && (
            <CRDTab crdYaml={crdYaml} crInstanceYaml={crInstanceYaml} rbacYaml={rbacYaml} />
          )}
          {activeTab === 'api' && (
            <APITab
              config={apiConfig}
              onChange={setApiConfig}
              status={apiStatus}
              onTest={handleTestConnection}
            />
          )}
          {activeTab === 'docs' && <DocsTab />}
        </div>
      </div>
    </div>
  );
}

